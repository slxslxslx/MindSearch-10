import openai
import json


JUDGE_PROMPT = """
You are an expert evaluator for Question Answering systems.

Your task is to determine whether a model's predicted answer correctly answers a given question based on the provided ground truth answers.

You will be given:

- a Question
- a list of Ground Truth Answers
- a Predicted Answer generated by an LLM

Your job is to judge whether the Predicted Answer is correct.

Evaluation Criteria:

1. The predicted answer does NOT need to exactly match the wording of the ground truth answer.
2. The predicted answer should be considered CORRECT if it is semantically equivalent to ANY of the ground truth answers.
3. Minor wording differences are acceptable as long as the meaning is the same.
4. If the predicted answer contradicts the ground truth, contains incorrect facts, or fails to answer the question, it should be marked INCORRECT.
5. If the predicted answer is vague, unrelated, or missing the key information needed to answer the question, it should be marked INCORRECT.

You must follow the evaluation steps below:

Step 1: Carefully compare the Predicted Answer with the Ground Truth Answers.

Step 2: Determine whether the meaning and key factual information in the ground truth answer appear in the predicted answer.

Step 3: Provide a short rationale explaining your reasoning.

Step 4: Output the final judgment.

Your response MUST be valid JSON and follow this format exactly:

{
    "rationale": "your explanation of the decision",
    "judgment": "correct" or "incorrect"
}

Now evaluate the following example:

Question:
{question}

Ground Truth Answers:
{gt_answers}

Predicted Answer:
{pred_answer}

Your output:
"""


def judge(question, answer, prediction, model="gpt-4o"):

    if isinstance(answer, str):
        answer = [answer]

    prompt = JUDGE_PROMPT.format(
        question=question,
        gt_answers =json.dumps(answer, ensure_ascii=False),
        pred_answer=prediction
    )

    response = openai.ChatCompletion.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        temperature=0
    )

    text = response["choices"][0]["message"]["content"]

    try:
        result = json.loads(text)

        judgment = result["judgment"].lower() # 提取 judgment 字段（转小写）

        return judgment == "correct", result

    except Exception:

        return False, {"error": "invalid_json", "raw_output": text}